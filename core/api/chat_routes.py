from __future__ import annotations

from datetime import datetime, timezone
from typing import Callable

from fastapi import (
    APIRouter,
    Depends,
    HTTPException,
    status,
)
from pydantic import (
    BaseModel,
    Field,
)

from core.foundation.moral_code.engine import guidance_for_generation


ConversationHandler = Callable[
    ...,
    dict[str, object],
]


class ChatRequest(
    BaseModel
):
    message: str = Field(
        min_length=1,
        max_length=8000,
    )


def utc_now_text() -> str:
    return datetime.now(
        timezone.utc
    ).isoformat()


def create_chat_router(
    require_api_authentication: Callable[..., None],
    *,
    chat_handler: ConversationHandler | None = None,
    memory_authorizer: Callable[..., object] | None = None,
) -> APIRouter:
    """
    Create ZÆNIA's protected local text-chat route.

    This route only performs conversation.

    It does not grant command execution authority.
    """

    active_chat_handler = (
        chat_handler
        if chat_handler is not None
        else None
    )

    router = APIRouter(
        tags=[
            "chat",
        ],
        dependencies=[
            Depends(
                require_api_authentication
            ),
        ],
    )

    @router.post(
        "/api/chat",
    )
    def chat(
        request: ChatRequest,
    ) -> dict[str, object]:
        """
        Send typed text through ZÆNIA's existing local
        conversation path.

        The normal conversation stack provides:

            recent conversation memory
            behavior context
            conversation context
            local Qwen / Ollama generation

        Text chat never receives system-command execution
        authority from this endpoint.
        """

        message = (
            request.message.strip()
        )

        if not message:
            raise HTTPException(
                status_code=(
                    status.HTTP_422_UNPROCESSABLE_ENTITY
                ),
                detail=(
                    "Chat message cannot be empty."
                ),
            )

        # This plain chat route can't set reminders or change tabs. When the model is asked to, it used to answer
        # "Done" without doing anything (2026-11-02), so say what actually happened.
        from core.assistant_platform import reminders as nudges
        if nudges.parse_request(message) is not None or nudges.is_reminder_request(message):
            return {"reply": "I can't set reminders from this chat. Use the ZÆNIA desktop app with the passkey unlocked, "
                             "then ask me again there. Nothing was saved."}
        try:
            handler = active_chat_handler
            if handler is None:
                from core.brain.dialogue_manager import converse
                handler = converse
            # Generation guidance is advisory; typed execution gates remain
            # independent of text generated by the model.
            guided_message = "[ZÆNIA owner moral compass]\n" + guidance_for_generation() + "\n\n[Owner message]\n" + message
            result = (
                handler(
                    guided_message,
                    speak_response=False,
                    attention_called=True,
                    **({"memory_authorizer": memory_authorizer} if active_chat_handler is None else {}),
                )
            )

        except RuntimeError as error:
            raise HTTPException(
                status_code=(
                    status.HTTP_503_SERVICE_UNAVAILABLE
                ),
                detail=str(
                    error
                ),
            ) from error

        except Exception as error:
            raise HTTPException(
                status_code=(
                    status.HTTP_500_INTERNAL_SERVER_ERROR
                ),
                detail=(
                    "ZÆNIA local chat failed."
                ),
            ) from error

        reply = str(
            result.get(
                "reply",
                "",
            )
            or ""
        ).strip()

        if not reply:
            raise HTTPException(
                status_code=(
                    status.HTTP_502_BAD_GATEWAY
                ),
                detail=(
                    "ZÆNIA brain returned an empty reply."
                ),
            )

        return {
            "success": True,
            "reply": reply,
            "spoken": False,
            "execution_authorized": False,
            "timestamp": (
                utc_now_text()
            ),
        }

    return router
